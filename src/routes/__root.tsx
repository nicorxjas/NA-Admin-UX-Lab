import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import {
  Outlet,
  Link,
  createRootRouteWithContext,
  redirect,
  useRouter,
  useRouterState,
  HeadContent,
  Scripts,
} from "@tanstack/react-router";
import { useEffect, type ReactNode } from "react";

import appCss from "../styles.css?url";
import { reportLovableError } from "../lib/lovable-error-reporting";
import { AdminSidebar } from "@/components/admin/AdminSidebar";
import { MasterDataProvider } from "@/lib/master-store";

const demoPaths = ["/recepcion", "/calidad"] as const;
const fallbackDemoPath = "/recepcion";

function isDemoPath(pathname: string) {
  return demoPaths.some((path) => pathname === path || pathname.startsWith(`${path}/`));
}

function NotFoundComponent() {
  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-7xl font-bold text-foreground">404</h1>
        <h2 className="mt-4 text-xl font-semibold text-foreground">Página no encontrada</h2>
        <p className="mt-2 text-sm text-muted-foreground">La ruta que buscas no existe.</p>
        <div className="mt-6">
          <Link
            to={fallbackDemoPath}
            className="inline-flex items-center justify-center rounded-md bg-primary px-4 py-2 text-sm font-medium text-primary-foreground transition-colors hover:bg-primary/90"
          >
            Volver a recepción
          </Link>
        </div>
      </div>
    </div>
  );
}

function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-semibold tracking-tight text-foreground">
          No pudimos cargar la página
        </h1>
        <p className="mt-2 text-sm text-muted-foreground">
          Algo salió mal. Podés reintentar o volver al inicio.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="inline-flex items-center justify-center rounded-md bg-primary px-4 py-2 text-sm font-medium text-primary-foreground transition-colors hover:bg-primary/90"
          >
            Reintentar
          </button>
          <a
            href={fallbackDemoPath}
            className="inline-flex items-center justify-center rounded-md border border-input bg-background px-4 py-2 text-sm font-medium text-foreground transition-colors hover:bg-accent"
          >
            Ir a recepción
          </a>
        </div>
      </div>
    </div>
  );
}

export const Route = createRootRouteWithContext<{ queryClient: QueryClient }>()({
  beforeLoad: ({ location }) => {
    if (isDemoPath(location.pathname)) return;

    throw redirect({
      to: fallbackDemoPath,
      replace: true,
    });
  },
  head: () => ({
    meta: [
      { charSet: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1" },
      { title: "Trazabilidad · Panel Administrador" },
      {
        name: "description",
        content:
          "Panel administrador para trazabilidad de fabricación de neumáticos: búsqueda de dependencias y carga de datos maestros por estación.",
      },
      { property: "og:title", content: "Trazabilidad · Panel Administrador" },
      {
        property: "og:description",
        content: "Panel administrador para trazabilidad de fabricación de neumáticos.",
      },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
    links: [
      { rel: "stylesheet", href: appCss },
      { rel: "icon", href: "/na-carrera-logo.png", type: "image/png" },
      { rel: "preconnect", href: "https://fonts.googleapis.com" },
      { rel: "preconnect", href: "https://fonts.gstatic.com", crossOrigin: "anonymous" },
      {
        rel: "stylesheet",
        href: "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap",
      },
    ],
  }),
  shellComponent: RootShell,
  component: RootComponent,
  notFoundComponent: NotFoundComponent,
  errorComponent: ErrorComponent,
});

function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="es" className="dark">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const currentPath = useRouterState({ select: (state) => state.location.pathname });
  const isDemoRoute = isDemoPath(currentPath);

  return (
    <QueryClientProvider client={queryClient}>
      <MasterDataProvider>
        <div
          className={
            isDemoRoute
              ? "min-h-screen w-full bg-background text-foreground"
              : "flex min-h-screen w-full bg-background text-foreground"
          }
        >
          {!isDemoRoute && <AdminSidebar />}
          <main className={isDemoRoute ? "min-h-screen w-full" : "flex-1 min-w-0"}>
            <Outlet />
          </main>
        </div>
      </MasterDataProvider>
    </QueryClientProvider>
  );
}
